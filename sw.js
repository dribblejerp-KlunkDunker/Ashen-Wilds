const CORE_CACHE = 'octave-core-' + BUILD;
const MEDIA_CACHE = 'octave-media-' + MEDIA_BUILD;
const SCOPE = self.registration.scope;                       // ends with a slash
const abs = (p) => new URL(p, SCOPE).href;
const BASE_PATH = new URL(SCOPE).pathname;
const relOf = (u) => new URL(u).pathname.slice(BASE_PATH.length);   // path under the scope
const INDEX = abs('index.html');
const MEDIA_SET = new Set(MEDIA.map(abs));
const inflight = new Map();                                  // url -> Promise<Response> of a media file being fetched whole
let cancelDownload = false;

async function precache() {
  const cache = await caches.open(CORE_CACHE);
  try {
    const todo = CORE.slice();
    const worker = async () => {
      for (let p = todo.shift(); p !== undefined; p = todo.shift()) {
        // cache: 'reload' skips the browser's HTTP cache (GitHub Pages serves max-age=600): the cached copy must be this build's
        const res = await fetch(new Request(abs(p), { cache: 'reload' }));
        if (!res.ok) throw new Error('precache ' + p + ' ' + res.status);
        await cache.put(abs(p), res.clone());
        if (p === 'index.html') await cache.put(SCOPE, res);       // the bare folder URL is the same page
      }
    };
    await Promise.all([worker(), worker(), worker(), worker(), worker(), worker()]);
  } catch (e) {
    await caches.delete(CORE_CACHE);                              // never leave a half-filled cache that could be mistaken for a build
    throw e;
  }
}

self.addEventListener('install', (event) => { event.waitUntil(precache()); });

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('octave-') && k !== CORE_CACHE && k !== MEDIA_CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

async function lookup(req) {
  const url = typeof req === 'string' ? req : req.url;
  for (const name of [CORE_CACHE, MEDIA_CACHE]) {
    const hit = await caches.match(url, { cacheName: name });
    if (hit) return hit;
  }
  // a different ?v= on a picture, font or sound is the same file; scripts and styles must match exactly (their ?v= is the version)
  const path = new URL(url).pathname;
  if (!/\.(js|css|html|webmanifest)$/.test(path)) {
    for (const name of [CORE_CACHE, MEDIA_CACHE]) {
      const hit = await caches.match(url, { cacheName: name, ignoreSearch: true });
      if (hit) return hit;
    }
  }
  return null;
}

// fetch a media file whole (never a range), store it, and share the one download between callers
function fetchWhole(url) {
  const key = url.split('?')[0];
  if (inflight.has(key)) return inflight.get(key).then((r) => r.clone());
  const p = (async () => {
    const res = await fetch(new Request(url, { cache: 'reload' }));
    if (res.ok && res.status === 200 && MEDIA_SET.has(abs(relOf(url)))) {
      const c = await caches.open(MEDIA_CACHE);
      await c.put(abs(relOf(url)), res.clone());
    }
    return res;
  })();
  inflight.set(key, p);
  const done = () => inflight.delete(key);
  p.then(done, done);
  return p.then((r) => r.clone());
}

async function rangeResponse(req) {
  let full = await lookup(req.url);
  if (!full) {
    const rel = relOf(req.url);
    if (!MEDIA_SET.has(abs(rel))) return fetch(req);              // not a file we cache: let the network answer the range
    try { full = await fetchWhole(abs(rel)); } catch (e) { return Response.error(); }
    if (!full.ok) return full;
  }
  const m = /^bytes=(\d*)-(\d*)$/.exec(req.headers.get('range') || '');
  const blob = await full.clone().blob();
  const size = blob.size;
  if (!m || (m[1] === '' && m[2] === '')) return new Response(blob, { status: 200, headers: { 'Content-Type': full.headers.get('Content-Type') || 'audio/mpeg', 'Content-Length': String(size), 'Accept-Ranges': 'bytes' } });
  let start, end;
  if (m[1] === '') { start = Math.max(0, size - Number(m[2])); end = size - 1; }      // bytes=-N: the last N bytes
  else { start = Number(m[1]); end = m[2] === '' ? size - 1 : Math.min(Number(m[2]), size - 1); }
  if (start >= size || start > end) return new Response(null, { status: 416, headers: { 'Content-Range': 'bytes */' + size } });
  return new Response(blob.slice(start, end + 1), { status: 206, headers: {
    'Content-Type': full.headers.get('Content-Type') || 'audio/mpeg', 'Content-Range': 'bytes ' + start + '-' + end + '/' + size,
    'Content-Length': String(end - start + 1), 'Accept-Ranges': 'bytes' } });
}

async function handle(event) {
  const req = event.request;
  if (req.mode === 'navigate') {
    const page = (await lookup(INDEX)) || (await lookup(SCOPE));
    if (page) return page;
    try { return await fetch(req); } catch (e) { return Response.error(); }
  }
  if (req.headers.has('range')) return rangeResponse(req);
  const hit = await lookup(req);
  if (hit) return hit;
  let res;
  try { res = await fetch(req); } catch (e) { return Response.error(); }
  const rel = relOf(req.url);
  if (res.ok && res.status === 200 && MEDIA_SET.has(abs(rel))) { const copy = res.clone(); event.waitUntil(caches.open(MEDIA_CACHE).then((c) => c.put(abs(rel), copy)).catch(() => { })); }
  return res;
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const u = new URL(req.url);
  if (u.origin !== self.location.origin || !u.href.startsWith(SCOPE)) return;
  if (u.pathname === BASE_PATH + 'sw.js') return;
  event.respondWith(handle(event));
});

async function mediaStatus() {
  const c = await caches.open(MEDIA_CACHE);
  const have = new Set((await c.keys()).map((r) => r.url));
  return { build: BUILD, total: MEDIA.length, cached: MEDIA.filter((p) => have.has(abs(p))).length, bytes: MEDIA_BYTES, scope: SCOPE, core: CORE.length };
}

async function downloadMedia(client) {
  cancelDownload = false;
  const c = await caches.open(MEDIA_CACHE);
  const have = new Set((await c.keys()).map((r) => r.url));
  const todo = MEDIA.filter((p) => !have.has(abs(p)));
  let done = MEDIA.length - todo.length, failed = 0;
  const say = (type) => { if (client) client.postMessage({ type, done, total: MEDIA.length, failed }); };
  say('media-progress');
  const worker = async () => {
    for (let p = todo.shift(); p !== undefined && !cancelDownload; p = todo.shift()) {
      try { const res = await fetch(new Request(abs(p), { cache: 'reload' })); if (!res.ok) throw new Error(String(res.status)); await c.put(abs(p), res); done++; } catch (e) { failed++; }
      say('media-progress');
    }
  };
  await Promise.all([worker(), worker(), worker()]);
  say(cancelDownload ? 'media-cancelled' : failed ? 'media-incomplete' : 'media-done');
}

self.addEventListener('message', (event) => {
  const d = event.data || {};
  if (d.type === 'skip-waiting') { self.skipWaiting(); return; }
  if (d.type === 'status') { event.waitUntil(mediaStatus().then((s) => event.source && event.source.postMessage(Object.assign({ type: 'status' }, s)))); return; }
  if (d.type === 'media-download') { event.waitUntil(downloadMedia(event.source)); return; }
  if (d.type === 'media-cancel') { cancelDownload = true; return; }
});
