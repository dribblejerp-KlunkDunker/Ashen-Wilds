#!/usr/bin/env python3
"""Generate scripts/data/lore_texts.gd from docs/worldbuilding/items-and-texts.md.

The world bible is the source; the game reads the generated constants. Run from the repo root after
editing the item lore or the notes in the bible:

    python3 tools/generate_lore_texts.py

It takes each item's "Proposed description" (section 1) and the notes listed in NOTES_IN_GAME
(section 4.1, the ones placed in containers or on the ground in the Act I level), checks that every
string is plain ASCII (the browser build has no system fonts), and writes the GDScript file.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs/worldbuilding/items-and-texts.md"
TARGET = ROOT / "scripts/data/lore_texts.gd"

# Display name in the bible -> item id in ItemDatabase.
ITEM_IDS = {
    "Tarnished Arming Sword": "arming_sword",
    "Boar-Lugged Spear": "boar_spear",
    "Woodsman's Broadaxe": "woodsmans_broadaxe",
    "Wooden Targe": "wooden_targe",
    "Pitch Torch": "pitch_torch",
    "Padded Coif": "padded_coif",
    "Kettle Hat": "kettle_hat",
    "Quilted Gambeson": "quilted_gambeson",
    "Rusted Mail Hauberk": "rusted_hauberk",
    "Leather Greaves": "leather_greaves",
    "Splinted Greaves": "splinted_greaves",
    "Clean Rag Bandage": "clean_rag_bandage",
    "Iron Scrap": "iron_scrap",
    "Salt Ration": "salt",
    "Seasoned Timber": "timber",
    "Flask of Lamp Oil": "lamp_oil",
    "Cast-Iron Cooking Pot": "cooking_pot",
}

# Note number in section 4.1 -> where the bootstrap puts it (a container's label, or "ground").
NOTES_IN_GAME = {
    1: "Shelter Stash", 2: "Shelter Stash", 21: "Shelter Stash",
    3: "Watchhouse Supply Chest", 4: "Watchhouse Supply Chest", 22: "Watchhouse Supply Chest",
    5: "Rotted Grain Crate", 6: "Rotted Grain Crate",
    9: "Ork Plunder Pile", 10: "Ork Plunder Pile", 20: "Ork Plunder Pile",
    11: "Gnawed Bone Heap", 12: "Gnawed Bone Heap",
    13: "Spore-Choked Cart", 19: "Spore-Choked Cart",
    16: "ground", 18: "ground", 25: "ground",
}


def fail(msg: str) -> None:
    print("generate_lore_texts: " + msg, file=sys.stderr)
    sys.exit(1)


def ascii_only(label: str, text: str) -> str:
    bad = sorted({c for c in text if ord(c) > 127})
    if bad:
        fail(f"{label} has non-ASCII characters {bad!r}; the browser build cannot draw them")
    return text


def main() -> None:
    md = SOURCE.read_text(encoding="utf-8")

    item_lore = {}
    for m in re.finditer(r"^### (.+?)\n(.*?)(?=^### |^## )", md, re.S | re.M):
        name, body = m.group(1).strip(), m.group(2)
        if name not in ITEM_IDS:
            continue
        d = re.search(r"\*\*Proposed description:\*\* `([^`]+)`", body)
        if not d:
            fail(f"no proposed description for {name}")
        item_lore[ITEM_IDS[name]] = ascii_only(name, d.group(1).strip())
    missing = set(ITEM_IDS.values()) - set(item_lore)
    if missing:
        fail(f"items without lore: {sorted(missing)}")

    notes = []
    for m in re.finditer(r"^\*\*(\d+)\. (.+?)\.\*\* \*(.+?)\*\n+```text\n(.*?)```", md, re.S | re.M):
        number = int(m.group(1))
        if number not in NOTES_IN_GAME:
            continue
        title = ascii_only(f"note {number} title", m.group(2).strip())
        text = ascii_only(f"note {number}", m.group(4).rstrip("\n"))
        notes.append({"id": "note_%02d" % number, "number": number, "title": title,
                      "place": NOTES_IN_GAME[number], "text": text})
    found = {n["number"] for n in notes}
    if found != set(NOTES_IN_GAME):
        fail(f"notes not found in the bible: {sorted(set(NOTES_IN_GAME) - found)}")

    out = [
        "class_name LoreTexts",
        "extends RefCounted",
        "## GENERATED by tools/generate_lore_texts.py from docs/worldbuilding/items-and-texts.md.",
        "## Do not edit by hand: edit the bible and run the generator.",
        "",
        "## Item id -> a line of lore, shown under the item's own description in its tooltip.",
        "const ITEM_LORE: Dictionary = {",
    ]
    for item_id in sorted(item_lore):
        out.append(f"\t{json.dumps(item_id)}: {json.dumps(item_lore[item_id])},")
    out += [
        "}",
        "",
        "## The notes placed in the Act I level. \"place\" is a container's label, or \"ground\" for a",
        "## note the bootstrap lays on the ground (NOTE_GROUND_SPOTS in scene_bootstrap.gd).",
        "const NOTES: Array[Dictionary] = [",
    ]
    for n in sorted(notes, key=lambda n: n["number"]):
        out.append("\t{\"id\": %s, \"title\": %s, \"place\": %s,\n\t\t\"text\": %s}," % (
            json.dumps(n["id"]), json.dumps(n["title"]), json.dumps(n["place"]), json.dumps(n["text"])))
    out += ["]", ""]
    TARGET.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(item_lore)} item lore lines, {len(notes)} notes")


if __name__ == "__main__":
    main()
